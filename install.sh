#!/bin/bash
# Timekeep installer / updater — issue #340.
#
# Fresh install:
#   curl -fsSL https://invoices.tristonarmstrong.com/releases/install.sh | bash
# Update to the latest v1 (re-running updates — data, token, and start.sh
# are preserved):
#   curl -fsSL https://invoices.tristonarmstrong.com/releases/install.sh | bash
#
# Env knobs:
#   INSTALL_DIR    where to install (default /opt/timekeep; needs root)
#   RELEASES_BASE  release feed origin (default the URL above)
#   PORT           port the server listens on (default 8080)
#
# Requirements: bun, curl, tar, sha256sum. The stop-detection uses /proc
# when available (Linux); otherwise the .pid file written by start.sh.
set -euo pipefail

INSTALL_DIR="${INSTALL_DIR:-/opt/timekeep}"
RELEASES_BASE="${RELEASES_BASE:-https://invoices.tristonarmstrong.com/releases}"
PORT="${PORT:-8080}"

say() { printf '%s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

for cmd in curl tar sha256sum bun; do
  command -v "$cmd" >/dev/null 2>&1 || die "$cmd is required but not installed."
done

if [ "$INSTALL_DIR" = "/opt/timekeep" ] && [ "$(id -u)" -ne 0 ]; then
  die "installing to /opt/timekeep needs root — re-run with sudo, or set INSTALL_DIR."
fi

# Resolve the latest v1 release from the feed. bun parses the JSON (it's a
# hard requirement already, so no python/jq needed).
read -r VERSION EXPECT_SHA TARBALL_URL < <(RELEASES_BASE="$RELEASES_BASE" bun -e '
  const base = process.env.RELEASES_BASE;
  const res = await fetch(base + "/feed.json");
  if (!res.ok) { console.error("error: could not fetch " + base + "/feed.json"); process.exit(1); }
  const feed = await res.json();
  const rel = feed.releases && feed.releases["1"];
  if (!rel || !rel.version || !rel.sha256 || !rel.url) {
    console.error("error: no v1 release published yet");
    process.exit(1);
  }
  console.log([rel.version, rel.sha256, rel.url].join(" "));
') || die "could not resolve a release from $RELEASES_BASE/feed.json"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

say "Downloading Timekeep v$VERSION ..."
curl -fsSL -o "$TMP/timekeep.tgz" "$TARBALL_URL"
ACTUAL_SHA="$(sha256sum "$TMP/timekeep.tgz" | cut -d' ' -f1)"
[ "$ACTUAL_SHA" = "$EXPECT_SHA" ] || die "checksum mismatch — the download may be corrupted, refusing to install."

mkdir -p "$TMP/new"
tar xzf "$TMP/timekeep.tgz" -C "$TMP/new" --strip-components=1
[ -f "$TMP/new/site/server.ts" ] || die "the tarball doesn't look like a Timekeep release."

# Stop a previous server. Primary: the .pid file written by start.sh.
# Fallback (Linux): bun processes whose working directory is the install dir.
stop_server() {
  local pids=""
  [ -f "$INSTALL_DIR/.pid" ] && pids="$(cat "$INSTALL_DIR/.pid" 2>/dev/null || true)"
  if [ -z "$pids" ] && [ -d /proc ]; then
    for pid in $(pgrep -x bun 2>/dev/null || true); do
      [ "$(readlink "/proc/$pid/cwd" 2>/dev/null || true)" = "$INSTALL_DIR" ] && pids="$pids $pid"
    done
  fi
  pids="$(printf '%s\n' $pids | sort -nu | tr '\n' ' ')"
  [ -z "${pids// }" ] && return 0
  say "Stopping the running server ..."
  # shellcheck disable=SC2086
  kill $pids 2>/dev/null || true
  for _ in $(seq 1 15); do
    local alive=""
    for pid in $pids; do kill -0 "$pid" 2>/dev/null && alive="$alive $pid"; done
    [ -z "${alive// }" ] && break
    sleep 1
  done
}

if [ -f "$INSTALL_DIR/site/server.ts" ]; then
  say "Updating $INSTALL_DIR to v$VERSION ..."
  stop_server
  # Clear everything except what must survive an update.
  ( cd "$INSTALL_DIR" && ls -A | grep -vx -e data -e .token -e start.sh -e .version -e .pid | xargs -r rm -rf )
  cp -a "$TMP/new/." "$INSTALL_DIR/"
else
  say "Installing Timekeep v$VERSION to $INSTALL_DIR ..."
  mkdir -p "$INSTALL_DIR/data"
  cp -a "$TMP/new/." "$INSTALL_DIR/"
  TOKEN="$(bun -e 'console.log(crypto.randomUUID().replace(/-/g, ""))')"
  printf '%s' "$TOKEN" > "$INSTALL_DIR/.token"
  chmod 600 "$INSTALL_DIR/.token"
  cat > "$INSTALL_DIR/start.sh" <<EOF
#!/bin/bash
# Timekeep — generated by install.sh. All runtime env lives here.
cd "\$(dirname "\$0")"
echo \$\$ > .pid
exec env TIMEKEEP_TOKEN="\$(cat .token)" DATA_DIR="\$PWD/data" PORT="$PORT" bun site/server.ts
EOF
  chmod +x "$INSTALL_DIR/start.sh"
fi

printf '%s' "$VERSION" > "$INSTALL_DIR/.version"

say "Starting Timekeep v$VERSION ..."
cd "$INSTALL_DIR" && setsid ./start.sh >/dev/null 2>&1 < /dev/null &
sleep 4
if curl -fsS "http://127.0.0.1:$PORT/login" >/dev/null 2>&1; then
  say "Timekeep v$VERSION is running at http://127.0.0.1:$PORT"
  [ -f "$INSTALL_DIR/.token" ] && say "API token: $INSTALL_DIR/.token"
else
  die "the server didn't come up — run $INSTALL_DIR/start.sh manually to see why."
fi
